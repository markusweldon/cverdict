/** "Copy as ticket": a Markdown summary of one CVE for Jira, GitHub or Linear, plus clipboard access. */
import type { CveDetail, Tier } from '../../shared/contract';
import { BRAND, REPO_URL } from '../../shared/brand';
import { cveOrgUrl, fmtPct, isHttpUrl, signed, vendorProduct } from './format';
import { TIER_META, verdict } from './tiers';

/**
 * CVE text is attacker-controlled. Neutralise Markdown that could turn into links, images, HTML or
 * formatting when the ticket is rendered, and keep it on one line. A zero-width space after `@`
 * stops GitHub from turning vendor handles ("@tanstack") into mentions; a backslash does not.
 */
export function mdEscape(text: string): string {
  return text
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/[\\`*_[\]<>|~]/g, (c) => `\\${c}`)
    .replace(/^([#>+-])/, '\\$1')
    .replace(/@/g, '@\u200b')
    .trim();
}

/** Inline code on one line: GitHub renders nothing inside it: no links, HTML, comments or mentions. */
export const mdCode = (text: string): string => `\`${text.replace(/`/g, '').replace(/[\r\n\t]+/g, ' ')}\``;

export function ticketMarkdown(d: CveDetail, tier: Tier, knob: number, pageUrl: string): string {
  const affected = d.affected[0];
  const what = affected ? vendorProduct(affected.vendor, affected.product) : d.cna;
  const v = verdict(d, tier, knob);
  const lines: string[] = [];
  lines.push(`### ${d.id} · ${mdEscape(what)}`);
  lines.push('');
  lines.push(`**Verdict:** ${v.head}: ${mdEscape(v.reason)} · score ${d.score.value}/100 (${TIER_META[tier].label}, evidence bar ${knob}, model ${mdEscape(d.score.model)})`);
  const summary = d.title ?? d.description;
  if (summary) lines.push(`**Summary:** ${mdEscape(summary.length > 300 ? `${summary.slice(0, 299)}…` : summary)}`);
  if (d.kev) {
    lines.push(`**CISA KEV:** added ${d.kev.date_added} · due **${d.kev.due_date}** · ransomware use: ${mdEscape(d.kev.ransomware)}${d.kev.forensic_triage ? ' · forensic triage required' : ''}`);
    if (d.kev.required_action) lines.push(`**Required action:** ${mdEscape(d.kev.required_action)}`);
  }
  lines.push('');
  lines.push('**Why**');
  for (const r of d.reasons) {
    if (r.polarity === 'unknown') continue;
    if (r.points === 0 && r.polarity !== 'info') continue;
    lines.push(`- ${r.polarity === 'info' ? 'info' : signed(r.points)} · ${mdEscape(r.label)}${r.url && isHttpUrl(r.url) ? ` (${r.url})` : ''}`);
  }
  if (d.unknowns.length > 0) {
    lines.push('');
    lines.push('**Unknowns**');
    for (const u of d.unknowns) lines.push(`- ${mdEscape(u)}`);
  }
  const facts: string[] = [];
  if (d.cvss) facts.push(`CVSS ${d.cvss.score.toFixed(1)}${d.cvss.severity ? ` ${mdEscape(d.cvss.severity)}` : ''} ${mdCode(d.cvss.vector)}`);
  if (d.epss) facts.push(`EPSS ${fmtPct(d.epss.score)} (${Math.floor(d.epss.percentile * 100)}th pct, ${d.epss.date})`);
  if (d.ssvc) facts.push(`SSVC ${mdEscape(`${d.ssvc.exploitation} / automatable ${d.ssvc.automatable} / ${d.ssvc.technical_impact}`)}`);
  if (d.cwe.length > 0) facts.push(d.cwe.map(mdEscape).join(', '));
  if (facts.length > 0) {
    lines.push('');
    lines.push(`**Facts:** ${facts.join(' · ')}`);
  }
  lines.push('');
  lines.push(`**Links:** ${pageUrl} · ${cveOrgUrl(d.id)}`);
  lines.push(`_Generated by ${BRAND.name} from public data. Quiet ≠ safe; exposure is yours to assess._`);
  return lines.join('\n');
}

/** "Disagree?": a prefilled score-feedback issue. Chip labels quote CNA text, so they go in as inline code. */
export function feedbackIssueUrl(d: CveDetail, tier: Tier, knob: number): string {
  const chips = d.reasons
    .filter((r) => r.points !== 0)
    .map((r) => `- ${signed(r.points)} ${mdCode(r.id)}: ${mdCode(r.label)}`)
    .join('\n');
  const body = `**CVE:** ${d.id}\n**Our verdict:** ${tier} · score ${d.score.value} with the evidence bar at ${knob} (model ${mdEscape(d.score.model)})\n\n**Chips**\n${chips}\n\n**What looks wrong?**\n<!-- Evidence links help most: an advisory, a KEV entry, an exploit, a patch. -->\n`;
  const q = new URLSearchParams({ title: `Score feedback: ${d.id}`, body, labels: 'score-feedback' });
  return `${REPO_URL}/issues/new?${q.toString()}`;
}

/** Clipboard write with a fallback for browsers or contexts without the async Clipboard API. */
export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    let ok = false;
    try {
      ok = document.execCommand('copy');
    } catch {
      ok = false;
    }
    ta.remove();
    return ok;
  }
}
