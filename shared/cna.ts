/**
 * CNAs that publish other vendors' CVEs in bulk (aggregators, CNAs of last resort, plugin
 * ecosystems): a big day from them is a release, not one vendor's patch day.
 */
const BULK_CNAS: ReadonlySet<string> = new Set(['vulncheck', 'vuldb', 'patchstack', 'wordfence', 'wpscan', 'github_m', 'mitre']);

/** "microsoft" → "Microsoft", "GitHub_M" → "GitHub"; others: "_" → space, lower-case words capitalised. */
export function cnaName(cna: string): string {
  const known = CNA_NAMES[cna.toLowerCase()];
  if (known) return known;
  return cna.replace(/_/g, ' ').replace(/(^|\s)([a-z])/g, (_, space: string, ch: string) => `${space}${ch.toUpperCase()}`);
}

/** True for aggregator CNAs whose big days are bulk releases rather than patch days. */
export function isBulkCna(cna: string): boolean {
  return BULK_CNAS.has(cna.toLowerCase());
}
